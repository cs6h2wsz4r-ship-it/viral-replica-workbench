const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const path=require('node:path');
const {createDocument}=require('./ui_test_dom');
const root=path.resolve(__dirname,'..');
async function main(){
  const document=createDocument();
  const html=fs.readFileSync(path.join(root,'web/index.html'),'utf8');
  document.body.innerHTML=html.slice(html.indexOf('<body>')+6,html.indexOf('</body>'));
  const $=s=>document.querySelector(s), requests=[];
  $('#updateDialog').showModal=()=>{$('#updateDialog').open=true;};
  $('#updateDialog').close=()=>{$('#updateDialog').open=false;};
  let result={phase:'idle',current_version:'old',message:'',available:null};
  let reject=false;
  const api=async(method,url,body)=>{requests.push({method,url,body});if(reject)throw Error('下载失败，当前代码未改变');return result;};
  vm.runInNewContext(fs.readFileSync(path.join(root,'web/update.js'),'utf8'),{document,api,location:{reload(){}},setTimeout});
  await $('#updatesBtn').onclick();
  assert.equal($('#updateDialog').open,true);
  assert.deepEqual(requests.map(r=>r.url),['updates']);
  assert.equal($('#applyUpdateBtn').hidden,true);
  result={...result,current_version:'20261114-0100',message:'当前已是最新发布版本。'};
  await $('#checkUpdateBtn').onclick();
  assert.equal(requests.at(-1).url,'updates/check');
  assert.equal(requests.at(-1).method,'POST');
  assert.equal($('#applyUpdateBtn').hidden,true);
  assert.match($('#updateInfo').textContent,/最新发布版本/);
  assert.doesNotMatch($('#updateDialog').textContent,/首次升级包|workbench-first-upgrade|update\.command|update\.bat/);
  result={...result,available:{sha:'a'.repeat(40),version:'new'},message:'发现新版本'};
  await $('#checkUpdateBtn').onclick();
  assert.equal($('#applyUpdateBtn').hidden,false);
  const before=requests.length;
  $('#applyUpdateBtn').onclick();
  assert.equal(requests.length,before,'showing confirmation must not install');
  assert.equal($('#updateConfirmation').hidden,false);
  assert.match($('#updateConfirmText').textContent,/项目、素材、Key、模型和依赖/);
  $('#cancelCodeUpdateBtn').onclick();
  assert.equal(requests.length,before);
  $('#applyUpdateBtn').onclick();
  result={phase:'done',current_version:'new',message:'代码已更新'};
  await $('#confirmCodeUpdateBtn').onclick();
  assert.equal(requests.at(-1).url,'updates/apply');
  assert.equal(requests.at(-1).body.sha,'a'.repeat(40));
  reject=true;await $('#checkUpdateBtn').onclick();
  assert.match($('#updateInfo').textContent,/下载失败/);
  assert.equal($('#checkUpdateBtn').disabled,false,'failure allows retry');
  $('#closeUpdateBtn').onclick();assert.equal($('#updateDialog').open,false);
  console.log('Code update UI: status, explicit check, confirm/cancel, pinned version, error recovery passed');
}
main().catch(e=>{console.error(e);process.exitCode=1;});
